#!/usr/bin/env node
/**
 * Writes src/tools/regodrill-release.ts: the regodrill version that the extension downloads, with the
 * SHA-256 and size of each platform's archive.
 *
 *   node scripts/update-regodrill.mjs 0.3.0
 *
 * For each archive, it downloads the file, checks it against the release's checksums.txt, and checks its
 * build provenance with `gh attestation verify` (GitHub CLI, signed by regodrill's release workflow). Any
 * failure stops the script, and the file is not written.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'adamaKomi/regodrill';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(ROOT, 'src', 'tools', 'regodrill-release.ts');

// `${process.platform}-${process.arch}` → goreleaser's archive name (regodrill's .goreleaser.yaml).
const PLATFORMS = {
  'darwin-arm64': (v) => `regodrill_${v}_darwin_arm64.tar.gz`,
  'darwin-x64': (v) => `regodrill_${v}_darwin_amd64.tar.gz`,
  'linux-arm64': (v) => `regodrill_${v}_linux_arm64.tar.gz`,
  'linux-x64': (v) => `regodrill_${v}_linux_amd64.tar.gz`,
  'win32-arm64': (v) => `regodrill_${v}_windows_arm64.zip`,
  'win32-x64': (v) => `regodrill_${v}_windows_amd64.zip`,
};

async function download(url) {
  const response = await fetch(url, { redirect: 'follow' });
  if (!response.ok) {
    throw new Error(`HTTP ${response.status} for ${url}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

const version = process.argv[2]?.replace(/^v/, '');
if (!version || !/^\d+\.\d+\.\d+$/.test(version)) {
  console.error('usage: node scripts/update-regodrill.mjs <version>, e.g. 0.3.0');
  process.exit(1);
}

const base = `https://github.com/${REPO}/releases/download/v${version}`;
const checksums = new Map(
  (await download(`${base}/checksums.txt`))
    .toString('utf8')
    .split('\n')
    .filter((line) => line.trim())
    .map((line) => {
      const [digest, name] = line.trim().split(/\s+\*?/);
      return [name, digest];
    })
);

const dir = mkdtempSync(join(tmpdir(), 'regodrill-release-'));
const assets = {};
try {
  for (const [platform, name] of Object.entries(PLATFORMS)) {
    const file = name(version);
    const expected = checksums.get(file);
    if (!expected) {
      throw new Error(`${file} is not in checksums.txt`);
    }
    const data = await download(`${base}/${file}`);
    const digest = createHash('sha256').update(data).digest('hex');
    if (digest !== expected) {
      throw new Error(`${file}: SHA-256 ${digest}, checksums.txt says ${expected}`);
    }
    const path = join(dir, file);
    writeFileSync(path, data);
    execFileSync('gh', ['attestation', 'verify', path, '--repo', REPO], { stdio: 'pipe' });
    assets[platform] = { file, sha256: digest, size: data.length };
    console.log(`${platform}: ${file} (${data.length} bytes) checksum and attestation OK`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}

const body = Object.entries(assets)
  .map(
    ([platform, a]) =>
      `    '${platform}': {\n      file: '${a.file}',\n      sha256: '${a.sha256}',\n      size: ${a.size},\n    },`
  )
  .join('\n');
writeFileSync(
  OUTPUT,
  `/**
 * The regodrill release that the extension downloads. Generated by scripts/update-regodrill.mjs, which checks
 * each archive against the release's checksums.txt and its build provenance attestation: do not edit by hand.
 */
import { RegodrillRelease } from './install';

export const REGODRILL_RELEASE: RegodrillRelease = {
  version: '${version}',
  assets: {
${body}
  },
};
`
);
console.log(`wrote ${OUTPUT}`);
